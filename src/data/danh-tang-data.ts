// ── AUTO-PROVINCE LOOKUP HELPER FUNCTION ──
export const getMonkLocation = (monk: Partial<MonkProfile>): { province: string; region: Region; coordinates: { x: number; y: number } } => {
  if (monk.province && monk.region && VIETNAM_PROVINCE_COORDINATES[monk.province]) {
    const coord = VIETNAM_PROVINCE_COORDINATES[monk.province];
    return { province: monk.province, region: monk.region, coordinates: { x: coord.numX, y: coord.numY } };
  }

  const nameLower = (monk.name || '').toLowerCase();

  for (const [key, loc] of Object.entries(KNOWN_MONK_LOCATIONS)) {
    if (nameLower.includes(key)) {
      const coord = VIETNAM_PROVINCE_COORDINATES[loc.province] || { numX: 43, numY: 21 };
      return { province: loc.province, region: loc.region, coordinates: { x: coord.numX, y: coord.numY } };
    }
  }

  // Fallback defaults by region
  if (monk.region === 'Miền Nam') {
    return { province: 'TP. Hồ Chí Minh', region: 'Miền Nam', coordinates: { x: 48, y: 78 } };
  }
  if (monk.region === 'Miền Trung') {
    return { province: 'Thừa Thiên Huế', region: 'Miền Trung', coordinates: { x: 58, y: 49 } };
  }
  if (monk.region === 'Quốc tế') {
    return { province: 'Quốc tế', region: 'Quốc tế', coordinates: { x: 88, y: 25 } };
  }

  return { province: 'Hà Nội', region: 'Miền Bắc', coordinates: { x: 43, y: 21 } };
};


export interface StoryQuoteBlock {
  type: 'poem' | 'prose';
  lines: string[];
  citation: string;
}

export interface StoryExternalLink {
  href: string;
  label: string;
}

export interface StoryBeat {
  id: string;
  /** Shared across a Prose slide and its follow-up Quote slide so the title stays anchored while body crossfades into quote */
  titleGroupId: string;
  /** Optional shared content key so rolling between two visuals for the exact same quote keeps text steady while only photo crossfades */
  contentGroupId?: string;
  slideKind: 'prose' | 'quote' | 'hub';
  beatLabel: string;
  mediaType: 'youtube' | 'image';
  youtubeId?: string;
  imageUrl: string;
  imageOrientation: 'portrait' | 'landscape';
  /** Desktop visual focal side: photo anchors to this side without cropping, text sits cleanly on the opposite side */
  focalSide: 'right' | 'left';
  /** Optional desktop layout override for landscape images: 'side' shifts landscape image all the way to focalSide */
  desktopLayout?: 'full' | 'side';
  imageStatus: 'video' | 'unique' | 'shared';
  /** Clean museum photo caption — strictly NO statue codes (TP00xx) */
  artifactTitle: string;
  /** Top headline line — rendered in UTM Niagara */
  headlineTop: string;
  /** Balanced sub-headline line — rendered in UTM ClassizismAntiqua matching visual width of headlineTop */
  headlineSub: string;
  /** Supports rich editorial inline markup: ***bold-italic gold***, **bold ivory**, *italic* */
  bodyText?: string;
  quote?: StoryQuoteBlock;
  /** Optional subtle editorial reading link (e.g. historical story at Chùa Hoằng Pháp) */
  externalLink?: StoryExternalLink;
}

